#!/usr/bin/env python3
"""Build assets/data/population_density.webp, the Population density layer.

Source: European Commission, Joint Research Centre, GHS-POP R2023A (Global
Human Settlement Layer population grid), epoch 2020, 30 arc-second grid in
WGS84 (EPSG:4326), about 1 km at the equator: people per cell, float64,
43202x21384, from 89.1 N to 89.1 S. CC BY 4.0. Pinned as `ghs-pop-e2020-30ss`
in data-sources.lock.json (a 482 MB zip; the GeoTIFF inside is a BigTIFF
with LZW tiles).

The script sums the people into a 4096x2048 equirectangular grid (each
source cell goes to the output cell holding its center), divides by each
output cell's area on the sphere, and writes the log of the density as one
8-bit channel (grey):

    0                 fewer than MIN_DENSITY people per km2 (no color)
    1 .. 255          log10 density from MIN_DENSITY to MAX_DENSITY, linear

`globe.frag` maps the value through the density color ramp
(`DENSITY_RAMP`), so the colors can change without rebuilding the data; the
legend reads the same ramp (`view::density_legend`). The image is a
lossless WebP (grey stored as RGB). Needs NumPy, Pillow, tifffile and
imagecodecs (for the LZW BigTIFF):

    pip install numpy Pillow tifffile imagecodecs
    python3 scripts/make_population_density.py          # fetch the pinned zip, then convert
    python3 scripts/make_population_density.py src.zip  # convert a local copy

It takes a few minutes (7 GB of float64 decoded tile by tile). The output is
not regenerated by CI; scripts/check-data.sh checks that it is a 4096x2048
WebP, and scripts/validate_data.py decodes it.
"""
import math
import os
import sys
import tempfile
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import data_sources  # noqa: E402

SOURCE = "ghs-pop-e2020-30ss"  # entry in data-sources.lock.json
MEMBER = "GHS_POP_E2020_GLOBE_R2023A_4326_30ss_V1_0.tif"
WIDTH, HEIGHT = 4096, 2048
# People per km2 at code 1 and code 255. Keep in step with
# `DENSITY_MIN`/`DENSITY_MAX` in src/view.rs.
MIN_DENSITY, MAX_DENSITY = 0.1, 50_000.0
EARTH_RADIUS_KM = 6371.0
OUT = os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "assets", "data", "population_density.webp"
)


def code(density):
    """The 8-bit code of a density (people per km2); works on NumPy arrays."""
    import numpy as np

    d = np.asarray(density, dtype=np.float64)
    lo, hi = math.log10(MIN_DENSITY), math.log10(MAX_DENSITY)
    with np.errstate(divide="ignore", invalid="ignore"):
        t = (np.log10(np.maximum(d, MIN_DENSITY)) - lo) / (hi - lo)
    c = 1 + np.round(np.clip(t, 0.0, 1.0) * 254)
    return np.where(d >= MIN_DENSITY, c, 0).astype(np.uint8)


def cell_areas_km2(height=HEIGHT, width=WIDTH):
    """Area on the sphere of one output cell in each row, north first."""
    import numpy as np

    edges = np.radians(90.0 - 180.0 * np.arange(height + 1) / height)
    band = 2 * math.pi * EARTH_RADIUS_KM**2 * (np.sin(edges[:-1]) - np.sin(edges[1:]))
    return band / width


def accumulate(tiles, origin, step, out_shape=(HEIGHT, WIDTH)):
    """Sum people into the output grid. `tiles` yields (array, row0, col0)
    in source cells; `origin` is the (lon, lat) of the source grid's top
    left corner and `step` its cell size in degrees. Negative and
    non-finite values (no data) count as no people."""
    import numpy as np

    h, w = out_shape
    total = np.zeros(h * w, dtype=np.float64)
    for data, row0, col0 in tiles:
        rows, cols = data.shape
        lat = origin[1] - (row0 + np.arange(rows) + 0.5) * step
        lon = origin[0] + (col0 + np.arange(cols) + 0.5) * step
        lon = (lon + 180.0) % 360.0 - 180.0
        oy = np.clip(np.floor((90.0 - lat) / 180.0 * h), 0, h - 1).astype(np.int64)
        ox = np.clip(np.floor((lon + 180.0) / 360.0 * w), 0, w - 1).astype(np.int64)
        v = np.where(np.isfinite(data) & (data > 0), data, 0.0)
        idx = (oy[:, None] * w + ox[None, :]).ravel()
        total += np.bincount(idx, weights=v.ravel(), minlength=h * w)
    return total.reshape(h, w)


def read_tiles(tif_path):
    """The GeoTIFF's tiles, its origin and its cell size."""
    import tifffile

    tif = tifffile.TiffFile(tif_path)
    page = tif.pages[0]
    tie = page.tags["ModelTiepointTag"].value
    scale = page.tags["ModelPixelScaleTag"].value
    origin, step = (tie[3], tie[4]), scale[0]
    if abs(scale[0] - scale[1]) > 1e-9 or abs(step - 1 / 120) > 1e-6:
        sys.exit(f"unexpected cell size {scale}")
    height, width = page.shape

    def tiles():
        for data, index, _shape in page.segments():
            row0, col0 = index[2], index[3]
            a = data.reshape(data.shape[1], data.shape[2])
            # Edge tiles are padded past the image.
            yield a[: height - row0, : width - col0], row0, col0

    return tiles(), origin, step, tif


def main():
    import numpy as np
    from PIL import Image

    src = sys.argv[1] if len(sys.argv) > 1 else None
    if src is None:
        try:
            src = data_sources.fetch(SOURCE)
        except (data_sources.DataSourceError, OSError) as e:
            sys.exit(f"error: {e}")
    with tempfile.TemporaryDirectory() as tmp:
        with zipfile.ZipFile(src) as z:
            tif_path = z.extract(MEMBER, tmp)
        tiles, origin, step, tif = read_tiles(tif_path)
        people = accumulate(tiles, origin, step)
        tif.close()
    density = people / cell_areas_km2()[:, None]
    codes = code(density)
    print(f"people: {people.sum() / 1e9:.3f} billion; cells with people: {(codes > 0).mean():.1%}")
    Image.fromarray(codes).convert("RGB").save(OUT, "WEBP", lossless=True, quality=100, method=6)
    print(f"wrote {os.path.normpath(OUT)}: {os.path.getsize(OUT)} bytes")


if __name__ == "__main__":
    main()
